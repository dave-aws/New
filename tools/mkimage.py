#!/usr/bin/env python3
"""Generate the kernel sector count used by stage 2's disk read loop."""
import os
import sys

SECTOR = 512
MAX_KERNEL_SECTORS = 16384 - 64  # kernel must live before the FS partition


def main():
    if len(sys.argv) != 3:
        sys.exit("usage: mkimage.py <kernel.bin> <out.inc>")
    path, out = sys.argv[1], sys.argv[2]
    size = os.path.getsize(path)
    sectors = (size + SECTOR - 1) // SECTOR
    if sectors > MAX_KERNEL_SECTORS:
        sys.exit(f"kernel too large: {sectors} sectors > {MAX_KERNEL_SECTORS}")
    with open(out, "w") as f:
        f.write("/* generated by tools/mkimage.py */\n")
        f.write(f".set KERNEL_SECTORS, {sectors}\n")
    print(f"kernel image: {size} bytes = {sectors} sectors")


if __name__ == "__main__":
    main()
