#!/usr/bin/env python3
"""Rasterise the built-in NOVA fonts from DejaVu (Bitstream Vera licence).

Outputs kernel/gui/font_data.c containing:
  * font_mono_8x16   - 1bpp terminal font, fixed 8x16 cell
  * font_ui          - 8bpp antialiased proportional UI font (~15 px)
  * font_ui_bold     - bold variant for titles
"""
import os
import sys

try:
    from PIL import Image, ImageDraw, ImageFont
except ImportError:
    sys.exit("Pillow is required; run with PYTHONPATH=.toolchain/root/usr/lib/python3/dist-packages")

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT_DIR = os.path.join(ROOT, ".toolchain/root/usr/share/fonts/truetype/dejavu")
OUT = os.path.join(ROOT, "kernel/gui/font_data.c")

FIRST, LAST = 32, 126
COUNT = LAST - FIRST + 1


def mono_font():
    font = ImageFont.truetype(os.path.join(FONT_DIR, "DejaVuSansMono.ttf"), 13)
    glyphs = []
    for code in range(FIRST, LAST + 1):
        img = Image.new("L", (8, 16), 0)
        d = ImageDraw.Draw(img)
        d.text((0, 12), chr(code), font=font, fill=255, anchor="ls")
        rows = []
        for y in range(16):
            bits = 0
            for x in range(8):
                if img.getpixel((x, y)) > 100:
                    bits |= 0x80 >> x
            rows.append(bits)
        glyphs.append(rows)
    return glyphs


def ui_font(path, size, height, baseline):
    font = ImageFont.truetype(path, size)
    glyphs = []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        advance = max(1, int(round(font.getlength(ch))))
        width = max(advance, 1)
        img = Image.new("L", (width, height), 0)
        d = ImageDraw.Draw(img)
        d.text((0, baseline), ch, font=font, fill=255, anchor="ls")
        data = bytearray()
        for y in range(height):
            for x in range(width):
                data.append(img.getpixel((x, y)))
        glyphs.append((advance, width, bytes(data)))
    return glyphs


def emit_mono(f, glyphs):
    f.write("/* generated by tools/mkfont.py - DejaVuSansMono 8x16, 1bpp */\n")
    f.write("#include <nova/types.h>\n#include <nova/fb.h>\n\n")
    f.write("const u8 nova_font_mono_8x16[%d][16] = {\n" % COUNT)
    for rows in glyphs:
        f.write("    {" + ",".join("0x%02x" % r for r in rows) + "},\n")
    f.write("};\n\n")


def emit_ui(f, name, glyphs, height, baseline):
    blob = bytearray()
    meta = []
    for advance, width, data in glyphs:
        meta.append((advance, width, len(blob)))
        blob += data
    f.write("/* %s */\n" % name)
    f.write("const u8 %s_bitmap[%d] = {\n" % (name, len(blob)))
    for i in range(0, len(blob), 24):
        f.write("    " + ",".join("0x%02x" % b for b in blob[i:i + 24]) + ",\n")
    f.write("};\n\n")
    f.write("const struct nova_glyph %s_glyphs[%d] = {\n" % (name, COUNT))
    for advance, width, offset in meta:
        f.write("    { %d, %d, %d },\n" % (advance, width, offset))
    f.write("};\n\n")
    f.write("const struct nova_font %s = { %s_glyphs, %s_bitmap, %d, %d, %d };\n\n"
            % (name, name, name, COUNT, height, baseline))


def main():
    mono = mono_font()
    ui = ui_font(os.path.join(FONT_DIR, "DejaVuSans.ttf"), 15, 20, 15)
    bold = ui_font(os.path.join(FONT_DIR, "DejaVuSans-Bold.ttf"), 15, 20, 15)
    with open(OUT, "w") as f:
        emit_mono(f, mono)
        emit_ui(f, "nova_font_ui", ui, 20, 15)
        emit_ui(f, "nova_font_ui_bold", bold, 20, 15)
    print(f"fonts written to {OUT} ({os.path.getsize(OUT)} bytes)")


if __name__ == "__main__":
    main()
