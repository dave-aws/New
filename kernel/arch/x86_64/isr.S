/* NOVA OS — interrupt entry stubs (x86-64).
 *
 * Every vector funnels through isr_common, which builds a struct regs on the
 * current kernel stack and hands it to trap_dispatch().  trap_dispatch may
 * return a different frame (context switch): we then continue unwinding from
 * the new thread's stack, which is how NOVA implements preemptive switching
 * without separate save/restore code.
 */
.code64
.intel_syntax noprefix

.macro ISR_NOERR n
.globl isr\n
isr\n:
    push 0
    push \n
    jmp   isr_common
.endm

.macro ISR_ERR n
.globl isr\n
isr\n:
    push \n
    jmp   isr_common
.endm

